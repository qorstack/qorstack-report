'use client'

// Test data autosave for the template editors. The saved test values live in the active version's
// sandboxPayload; Generate and Auto-preview persist them on the server, and this hook saves edits in
// between (debounced) through the same templatesUpdate call Rename uses.

import React, { useCallback, useEffect, useRef, useState } from 'react'
import { api } from '@/api/generated/main-service'
import Icon from '@/components/icon'

const AUTOSAVE_DELAY_MS = 1500

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v)

const hasInlineData = (v: unknown): boolean => {
  if (typeof v === 'string') return v.startsWith('data:')
  if (Array.isArray(v)) return v.some(hasInlineData)
  if (isRecord(v)) return Object.values(v).some(hasInlineData)
  return false
}

/**
 * Replaces inline `data:` strings (base64 images) — too large for the URL query templatesUpdate sends.
 * Each one falls back to the value stored on the server at the same path (a file URL saved by the last
 * Generate), or null when the server has none, so saving never drops an image that was already stored.
 */
export const stripInlineData = (value: unknown, stored?: unknown): unknown => {
  if (typeof value === 'string') {
    if (!value.startsWith('data:')) return value
    return typeof stored === 'string' && !stored.startsWith('data:') ? stored : null
  }
  if (Array.isArray(value)) return value.map((v, i) => stripInlineData(v, Array.isArray(stored) ? stored[i] : undefined))
  if (isRecord(value)) {
    const out: Record<string, unknown> = {}
    Object.entries(value).forEach(([k, v]) => {
      out[k] = stripInlineData(v, isRecord(stored) ? stored[k] : undefined)
    })
    return out
  }
  return value
}

const parsePayload = (json?: string | null): unknown => {
  if (!json) return undefined
  try {
    return JSON.parse(json)
  } catch {
    return undefined
  }
}

/** Payload safe to send to templatesUpdate. Reads the stored payload only when there is inline data to replace. */
export const toStorablePayload = async (templateKey: string, payload: unknown): Promise<string> => {
  if (!hasInlineData(payload)) return JSON.stringify(payload)
  let stored: unknown
  try {
    const template = await api.templates.getTemplateById(templateKey)
    stored = parsePayload(template.sandboxPayload)
  } catch {
    stored = undefined
  }
  return JSON.stringify(stripInlineData(payload, stored))
}

export type TestDataSaveStatus = 'idle' | 'pending' | 'saving' | 'saved' | 'error'

interface Options<T> {
  templateKey: string
  state: T
  /** UI state → the payload stored as sandboxPayload. */
  serialize: (state: T) => unknown
  /** Off while loading, or while Auto-preview already saves each render. */
  enabled: boolean
}

export const useTestDataAutosave = <T,>({ templateKey, state, serialize, enabled }: Options<T>) => {
  const [status, setStatus] = useState<TestDataSaveStatus>('idle')
  /** JSON of the payload the server already has — edits are compared against it. */
  const savedJsonRef = useRef<string | null>(null)
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null)
  const latestRef = useRef({ templateKey, state, serialize })
  // Declared first so every later effect (and a save fired from a timer) sees this render's values.
  useEffect(() => {
    latestRef.current = { templateKey, state, serialize }
  })

  const clearTimer = () => {
    if (timerRef.current) clearTimeout(timerRef.current)
    timerRef.current = null
  }

  /**
   * Record that the server holds this state (after load, Generate or Rename). A pending save is kept
   * only when the editor has moved on since (edits made while Generate was running).
   */
  const markSaved = useCallback((saved: T) => {
    const { serialize: toPayload, state: latest } = latestRef.current
    savedJsonRef.current = JSON.stringify(toPayload(saved))
    if (timerRef.current && JSON.stringify(toPayload(latest)) !== savedJsonRef.current) return
    clearTimer()
    setStatus(s => (s === 'idle' ? 'idle' : 'saved'))
  }, [])

  const save = useCallback(async () => {
    clearTimer()
    const { templateKey: key, state: current, serialize: toPayload } = latestRef.current
    if (!key) return
    const payload = toPayload(current)
    const json = JSON.stringify(payload)
    if (json === savedJsonRef.current) {
      setStatus(s => (s === 'idle' ? 'idle' : 'saved'))
      return
    }
    setStatus('saving')
    try {
      await api.templates.templatesUpdate(
        key,
        { sandboxPayload: await toStorablePayload(key, payload), isAutoGeneratedVariable: false },
        {}
      )
      savedJsonRef.current = json
      // Newer edits during the request schedule their own save via the effect below.
      setStatus(JSON.stringify(latestRef.current.serialize(latestRef.current.state)) === json ? 'saved' : 'pending')
    } catch {
      setStatus('error')
    }
  }, [])

  useEffect(() => {
    if (!enabled || savedJsonRef.current == null) return
    const json = JSON.stringify(serialize(state))
    if (json === savedJsonRef.current) {
      // Edited back to what is already saved.
      if (timerRef.current) {
        clearTimer()
        setStatus('saved')
      }
      return
    }
    setStatus(s => (s === 'saving' ? s : 'pending'))
    clearTimer()
    timerRef.current = setTimeout(() => void save(), AUTOSAVE_DELAY_MS)
    // serialize is a stable module-level converter in both editors.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [state, enabled, save])

  // Unsaved edits: warn before the tab closes; flush a pending save when the editor unmounts.
  const unsaved = status === 'pending' || status === 'saving' || status === 'error'
  useEffect(() => {
    if (!unsaved) return
    const onBeforeUnload = (e: BeforeUnloadEvent) => {
      e.preventDefault()
      e.returnValue = ''
    }
    window.addEventListener('beforeunload', onBeforeUnload)
    return () => window.removeEventListener('beforeunload', onBeforeUnload)
  }, [unsaved])

  useEffect(
    () => () => {
      if (timerRef.current) void save()
    },
    [save]
  )

  return { status, markSaved, retry: save }
}

/** Quiet save indicator for the fields panel head. */
export const TestDataSaveIndicator: React.FC<{ status: TestDataSaveStatus; onRetry: () => void }> = ({
  status,
  onRetry
}) => {
  if (status === 'idle') return null
  if (status === 'error') {
    return (
      <span role='alert' className='flex items-center gap-1.5 px-3 text-[12px] text-danger'>
        <Icon icon='lucide:triangle-alert' className='h-3.5 w-3.5' />
        Test values not saved
        <button type='button' onClick={onRetry} className='underline underline-offset-4 hover:text-foreground'>
          Retry
        </button>
      </span>
    )
  }
  return (
    <span role='status' className='flex items-center gap-1.5 px-3 text-[12px] text-default-500'>
      {status === 'saved' ? (
        <>
          <Icon icon='lucide:check' className='h-3.5 w-3.5' />
          Test values saved
        </>
      ) : (
        <>
          <Icon icon='lucide:loader-2' className='h-3.5 w-3.5 animate-spin' />
          Saving…
        </>
      )}
    </span>
  )
}
